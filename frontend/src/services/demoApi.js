const startDate = Date.UTC(2024, 0, 1);
const endDate = Date.UTC(2026, 8, 1);
const countryByCode = new Map(COUNTRIES.map((country) => [country.code, country]));

export const PROJECTS = Array.from({ length: 500 }, (_, index) => {
  const company = index < COUNTRIES.length
    ? COMPANIES.find((item) =>
        item.headquarters_country !== COUNTRIES[index].code)
    : index < COMPANIES.length
      ? COMPANIES[index]
      : pick(COMPANIES);
  const sector = index < SECTORS.length
    ? SECTORS[index]
    : pick(SECTORS);
  const source = countryByCode.get(company.headquarters_country);
  let destination = index < COUNTRIES.length
    ? COUNTRIES[index]
    : pick(COUNTRIES);

  if (destination.code === source.code) {
    destination = COUNTRIES[(COUNTRIES.indexOf(destination) + 1) % COUNTRIES.length];
  }

  const capex = Math.round(
    (5_000_000 + random() * 1_995_000_000) / 1000
  ) * 1000;
  const jobs = 50 + Math.floor(random() * 4951);
  const projectType = random() < 0.6 ? "Greenfield" : "Expansion";
  const statusDraw = random();
  const status = statusDraw < 0.5
    ? "announced"
    : statusDraw < 0.8
      ? "confirmed"
      : "operational";
  const date = new Date(
    startDate + Math.floor(random() * (endDate - startDate))
  ).toISOString().slice(0, 10);

  return {
    id: index + 1,
    company_id: company.id,
    company: company.name,
    source_country: source.code,
    destination_country: destination.code,
    sector: sector.name,
    sector_cluster: sector.cluster,
    project_type: projectType,
    capex_usd: capex,
    jobs_created: jobs,
    announcement_date: date,
    status,
    description:
      company.name + " announced a " + projectType.toLowerCase() +
      " investment in " + destination.name + " in the " +
      sector.name + " sector. The proposed project involves approximately $" +
      capex.toLocaleString("en-US") + " of capital investment and " +
      jobs.toLocaleString("en-US") + " potential jobs."
  };
});

const sum = (rows, key) =>
  rows.reduce((total, row) => total + (row[key] || 0), 0);
const matches = (value, term) =>
  String(value || "").toLowerCase().includes(String(term).toLowerCase());
const sortDescending = (a, b, key) => b[key] - a[key];

export async function getSummary() {
  return {
    total_projects: PROJECTS.length,
    total_capex_usd: sum(PROJECTS, "capex_usd"),
    total_jobs: sum(PROJECTS, "jobs_created"),
    countries_count: new Set(
      PROJECTS.map((project) => project.destination_country)
    ).size
  };
}

function aggregateBy(key) {
  const grouped = new Map();

  for (const project of PROJECTS) {
    const id = project[key];
    const row = grouped.get(id) || {
      project_count: 0,
      total_capex_usd: 0,
      total_jobs: 0
    };
    row.project_count += 1;
    row.total_capex_usd += project.capex_usd;
    row.total_jobs += project.jobs_created;
    grouped.set(id, row);
  }

  return grouped;
}

export async function getTopDestinations() {
  return [...aggregateBy("destination_country").entries()]
    .map(([country, stats]) => ({ country, ...stats }))
    .sort((a, b) => sortDescending(a, b, "project_count"))
    .slice(0, 10);
}

export async function getTopSectors() {
  return [...aggregateBy("sector").entries()]
    .map(([sector, stats]) => ({ sector, ...stats }))
    .sort((a, b) => sortDescending(a, b, "total_capex_usd"))
    .slice(0, 10);
}

export async function getTrends() {
  const monthly = [...aggregateBy("announcement_date").entries()]
    .reduce((monthly, [date, stats]) => {
      const month = date.slice(0, 7);
      const row = monthly.get(month) || {
        month,
        project_count: 0,
        total_capex_usd: 0,
        total_jobs: 0
      };
      row.project_count += stats.project_count;
      row.total_capex_usd += stats.total_capex_usd;
      row.total_jobs += stats.total_jobs;
      monthly.set(month, row);
      return monthly;
    }, new Map());

  return [...monthly.values()].sort((a, b) => a.month.localeCompare(b.month));
}

export async function getMapData() {
  return [...aggregateBy("destination_country").entries()]
    .map(([code, stats]) => {
      const country = countryByCode.get(code);
      return {
        country_code: country.code,
        country_name: country.name,
        region: country.region,
        latitude: country.latitude,
        longitude: country.longitude,
        ...stats
      };
    })
    .sort((a, b) => sortDescending(a, b, "project_count"));
}

export async function getProjects(params = {}) {
  const page = Math.max(1, Number(params.page) || 1);
  const pageSize = Math.max(1, Math.min(100, Number(params.page_size) || 25));

  let filtered = PROJECTS.filter((project) => {
    if (params.destination_country &&
        project.destination_country !== String(params.destination_country).toUpperCase()) return false;
    if (params.source_country &&
        project.source_country !== String(params.source_country).toUpperCase()) return false;
    if (params.sector && !matches(project.sector, params.sector)) return false;
    if (params.company_name && !matches(project.company, params.company_name)) return false;
    if (params.project_type && !matches(project.project_type, params.project_type)) return false;
    if (params.year_from && Number(project.announcement_date.slice(0, 4)) < Number(params.year_from)) return false;
    if (params.year_to && Number(project.announcement_date.slice(0, 4)) > Number(params.year_to)) return false;
    if (params.min_capex != null && project.capex_usd < Number(params.min_capex)) return false;
    if (params.max_capex != null && project.capex_usd > Number(params.max_capex)) return false;
    return true;
  });

  const sortKeys = new Set([
    "announcement_date", "capex_usd", "jobs_created", "company", "sector"
  ]);
  const sortKey = sortKeys.has(params.sort_by)
    ? params.sort_by : "announcement_date";
  const direction = String(params.sort_order).toLowerCase() === "asc"
    ? 1 : -1;

  filtered = filtered.sort((a, b) => {
    const left = a[sortKey];
    const right = b[sortKey];
    const comparison = typeof left === "number"
      ? left - right : String(left).localeCompare(String(right));
    return direction * comparison || (a.id - b.id);
  });

  const total = filtered.length;
  const items = filtered.slice((page - 1) * pageSize, page * pageSize);
  return {
    total,
    page,
    page_size: pageSize,
    results_on_page: items.length,
    items
  };
}

export async function searchGlobal(query, limit = 5) {
  const term = String(query || "").trim();
  const maxResults = Math.max(1, Math.min(10, Number(limit) || 5));

  if (term.length < 2) {
    return {
      query: term,
      companies: [],
      projects: [],
      countries: [],
      sectors: []
    };
  }

  const companies = COMPANIES
    .filter((company) =>
      [company.name, company.industry, company.description]
        .some((value) => matches(value, term)))
    .sort((a, b) => a.name.localeCompare(b.name))
    .slice(0, maxResults);

  const countries = COUNTRIES
    .filter((country) =>
      [country.code, country.name, country.region]
        .some((value) => matches(value, term)))
    .sort((a, b) => a.name.localeCompare(b.name))
    .slice(0, maxResults);

  const sectors = SECTORS
    .filter((sector) =>
      [sector.name, sector.cluster].some((value) => matches(value, term)))
    .map((sector, index) => ({
      id: SECTORS.indexOf(sector) + 1,
      ...sector
    }))
    .slice(0, maxResults);

  const projects = PROJECTS
    .filter((project) =>
      [
        project.company, project.sector, project.sector_cluster,
        project.description, project.project_type,
        project.source_country, project.destination_country,
        countryByCode.get(project.source_country).name,
        countryByCode.get(project.destination_country).name
      ].some((value) => matches(value, term)))
    .sort((a, b) => b.announcement_date.localeCompare(a.announcement_date))
    .slice(0, maxResults);

  return { query: term, companies, projects, countries, sectors };
}
